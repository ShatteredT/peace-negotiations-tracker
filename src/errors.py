"""Типи помилок застосунку.

* ``NoteError`` та нащадки — ОЧІКУВАНІ відмови (некоректний ввід, конфлікт, немає прав).
  Їхній текст безпечно показувати користувачу.
* ``TechnicalFailure`` — збій інфраструктури (БД недоступна, пошкоджений файл тощо).
  Текст містить код ``request_id``, за яким подію можна знайти в журналі (logs/ops.jsonl).
"""


class NoteError(Exception):
    """Базовий клас очікуваних (бізнес) помилок."""


class ValidationError(NoteError):
    """Некоректні вхідні дані: порожній текст, дата поза допустимим діапазоном, невідома категорія."""


class ConflictError(NoteError):
    """Операція суперечить поточному стану: слот зайнятий, замітка вже в архіві."""


class AccessDenied(NoteError):
    """У користувача немає прав на цю дію (чужа замітка)."""


class NotFoundError(NoteError):
    """Замітки з таким ідентифікатором не існує."""


class TechnicalFailure(Exception):
    """Технічний збій. Не показує деталей користувачу, лише код для пошуку в журналі."""

    def __init__(self, request_id: str):
        super().__init__(f"Технічна помилка. Код для пошуку в журналі: {request_id}")
        self.request_id = request_id
